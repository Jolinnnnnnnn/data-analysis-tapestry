     "- Ratios (aov, upt, aur, shares) are computed from totals for each window, never averaged.",
     "- Shares: genz_share_of_new, genz_share_of_txns, returning_share, new_insider_rate, genz_new_insider_rate, outlet_share, ecomm_share → `{ty, ly, chg_pts}`.",
