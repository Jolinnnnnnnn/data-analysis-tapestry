def ex(s):
    v = s.dropna().unique()[:4]
    return "; ".join(str(x)[:24] for x in v)


L = ["# Data dictionary", "", "Generated by scripts/13_docs.py from data/processed/lines.csv & inventory.csv. Decisions referenced as D# (DECISIONS.md), findings as F# (FINDINGS.md).", "",
     "## Data sheet → data/processed/lines.csv", "", f"Rows: {len(d)} (TY {int((d.YEAR=='TY').sum())}, LY {int((d.YEAR=='LY').sum())}). Grain: one transaction (= one line).", "",
     "| column | source | dtype | n_distinct | nulls | examples | definition (workbook) | analyst notes |", "|---|---|---|---|---|---|---|---|"]
for c in d.columns:
    src = "raw" if c in defs else "derived"
    definition = defs.get(c, DERIVED.get(c, "")).replace("|", "/")
    L.append(f"| {c} | {src} | {d[c].dtype} | {d[c].nunique()} | {int(d[c].isna().sum())} | {ex(d[c])} | {definition} | {NOTES.get(c, '')} |")
L += ["", "## Inventory sheet → data/processed/inventory.csv", "", f"Rows: {len(inv)} = {inv.STYLE_GROUP.nunique()} families × {inv.WK.nunique()} weeks × {inv.YEAR.nunique()} years. Grain: family × fiscal week snapshot.", "",
      "| column | source | dtype | n_distinct | examples | definition (workbook) | analyst notes |", "|---|---|---|---|---|---|---|"]
for c in inv.columns:
    src = "raw" if c in inv_defs else "derived"
    definition = inv_defs.get(c, {"YEAR": "TY/LY", "WK": "integer week", "PROD_CATEGORY": "joined from Data hierarchy", "PROD_TYPE": "joined from Data hierarchy"}.get(c, "")).replace("|", "/")
    L.append(f"| {c} | {src} | {inv[c].dtype} | {inv[c].nunique()} | {ex(inv[c])} | {definition} | {NOTES.get(c, '')} |")
L += ["", "## Hierarchy", "", d.groupby(["PROD_CATEGORY", "STYLE_GROUP", "PROD_TYPE"]).STYLE_DESC.unique().apply(lambda x: ", ".join(sorted(x))).reset_index()
      .rename(columns={"STYLE_DESC": "styles"}).to_markdown(index=False)]
(TAB / "data_dictionary.md").write_text("\n".join(L))

